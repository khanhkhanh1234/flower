import fs from 'node:fs';

/** Shop time zone: timestamps are stored as local 'YYYY-MM-DD HH:MM:SS' text. */
export const TZ = 'Asia/Ho_Chi_Minh';
export const NOW = `to_char(now() AT TIME ZONE '${TZ}', 'YYYY-MM-DD HH24:MI:SS')`;

const ID = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
const TABLES = [
  'users', 'sessions', 'settings', 'customers', 'flowers', 'branches', 'staff',
  'orders', 'order_items', 'order_images', 'order_events', 'import_notes',
];

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id ${ID},
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'staff',
  created_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE IF NOT EXISTS customers (
  id ${ID},
  name TEXT NOT NULL,
  phone TEXT,
  address TEXT,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW},
  deleted_at TEXT
);

CREATE TABLE IF NOT EXISTS flowers (
  id ${ID},
  name TEXT NOT NULL,
  price INTEGER NOT NULL DEFAULT 0,
  image TEXT,
  description TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW},
  deleted_at TEXT
);

CREATE TABLE IF NOT EXISTS branches (
  id ${ID},
  name TEXT NOT NULL,
  address TEXT,
  deleted_at TEXT
);

CREATE TABLE IF NOT EXISTS staff (
  id ${ID},
  name TEXT NOT NULL,
  phone TEXT,
  branch_id INTEGER REFERENCES branches(id),
  deleted_at TEXT
);

CREATE TABLE IF NOT EXISTS orders (
  id ${ID},
  code TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  is_draft INTEGER NOT NULL DEFAULT 0,
  customer_id INTEGER REFERENCES customers(id),
  order_for TEXT NOT NULL DEFAULT 'self',
  customer_name TEXT,
  customer_phone TEXT,
  recipient_name TEXT,
  recipient_phone TEXT,
  address TEXT,
  delivery_date TEXT,
  delivery_time TEXT,
  platform TEXT,
  price INTEGER NOT NULL DEFAULT 0,
  ship_fee INTEGER NOT NULL DEFAULT 0,
  discount INTEGER NOT NULL DEFAULT 0,
  discount_type TEXT NOT NULL DEFAULT 'vnd',
  extra_cost INTEGER NOT NULL DEFAULT 0,
  deposit_status TEXT NOT NULL DEFAULT 'none',
  deposit_amount INTEGER NOT NULL DEFAULT 0,
  product_summary TEXT,
  branch_id INTEGER REFERENCES branches(id),
  staff_id INTEGER REFERENCES staff(id),
  note TEXT,
  created_by TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW},
  updated_at TEXT NOT NULL DEFAULT ${NOW},
  deleted_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_orders_delivery ON orders(delivery_date);

CREATE TABLE IF NOT EXISTS order_items (
  id ${ID},
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  flower_id INTEGER REFERENCES flowers(id),
  name TEXT NOT NULL,
  unit_price INTEGER NOT NULL DEFAULT 0,
  qty INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS order_images (
  id ${ID},
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  path TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_images_order ON order_images(order_id);

CREATE TABLE IF NOT EXISTS order_events (
  id ${ID},
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  by_user TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS import_notes (
  date TEXT PRIMARY KEY,
  content TEXT
);

-- Supabase exposes the public schema through its REST API. With RLS on and no
-- policies, those API roles see nothing; this server connects as the table owner.
${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;

/** Our SQL uses `?` placeholders (never a literal '?'); Postgres wants $1, $2… */
const toPg = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

/** exec(sql, params) -> Promise<{ rows, changes }> */
function wrap(exec) {
  const run = (sql, params) => exec(toPg(sql), params.map((p) => (p === undefined ? null : p)));
  return {
    all: async (sql, ...params) => (await run(sql, params)).rows,
    get: async (sql, ...params) => (await run(sql, params)).rows[0],
    run: (sql, ...params) => run(sql, params),
  };
}

function readCa(value) {
  if (!value) return undefined;
  if (value.includes('-----BEGIN')) return value;
  try {
    return fs.readFileSync(value, 'utf8');
  } catch {
    throw new Error(`Không đọc được file chứng chỉ DATABASE_CA: ${value}`);
  }
}

async function openPostgres(url) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(20, Number); // int8 (COUNT/SUM) -> number
  pg.types.setTypeParser(1700, Number); // numeric -> number
  // TLS is configured below; drop ssl* URL params so they can't override it.
  const u = new URL(url);
  for (const k of [...u.searchParams.keys()]) if (k.startsWith('ssl')) u.searchParams.delete(k);
  const ca = readCa(process.env.DATABASE_CA);
  const ssl = process.env.DATABASE_SSL === 'off' ? false : { rejectUnauthorized: true, ...(ca ? { ca } : {}) };
  const pool = new pg.Pool({ connectionString: u.toString(), ssl, max: 5, idleTimeoutMillis: 30000 });
  pool.on('error', (e) => console.error('Lỗi kết nối DB:', e.message));
  const norm = (r) => ({ rows: r.rows, changes: r.rowCount ?? 0 });
  await pool.query(SCHEMA);
  return {
    ...wrap((sql, params) => pool.query(sql, params).then(norm)),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const r = await fn(wrap((sql, params) => client.query(sql, params).then(norm)));
        await client.query('COMMIT');
        return r;
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function openEmbedded(dir) {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir) fs.mkdirSync(dir, { recursive: true });
  const lite = dir ? new PGlite(dir) : new PGlite();
  await lite.exec(SCHEMA);
  const norm = (r) => ({ rows: r.rows, changes: r.affectedRows ?? 0 });
  return {
    ...wrap((sql, params) => lite.query(sql, params).then(norm)),
    tx: (fn) => lite.transaction((t) => fn(wrap((sql, params) => t.query(sql, params).then(norm)))),
    close: () => lite.close(),
  };
}

/**
 * Open the database. With `url` (e.g. Supabase) use a real Postgres server;
 * otherwise use embedded Postgres (PGlite) stored in `dir` (in-memory if omitted).
 */
export function openDb({ url, dir } = {}) {
  return url ? openPostgres(url) : openEmbedded(dir);
}
